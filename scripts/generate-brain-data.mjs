// Regenerates public/brain/ and app/data/brains.ts from assets/brain/.
// Run after adding/removing scan folders or frames:
//   node scripts/generate-brain-data.mjs
// Per-folder playback speed lives in Hero.tsx (<BrainLoops fps={{...}} />).

import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "assets", "brain");
const OUT = join(root, "public", "brain");
const DATA = join(root, "app", "data", "brains.ts");

const folders = readdirSync(SRC, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

// Clear previous frame folders but preserve volume/, which is owned by
// scripts/build-brain-volume.mjs (regenerate it separately if brain2 changed).
mkdirSync(OUT, { recursive: true });
for (const entry of readdirSync(OUT, { withFileTypes: true })) {
  if (entry.name === "volume") continue;
  rmSync(join(OUT, entry.name), { recursive: true, force: true });
}

const scans = folders.map((folder) => {
  const nums = readdirSync(join(SRC, folder))
    .map((f) => /^image_(\d+)\.png$/.exec(f))
    .filter(Boolean)
    .map((m) => Number(m[1]))
    .sort((a, b) => a - b);
  cpSync(join(SRC, folder), join(OUT, folder), { recursive: true });
  return { folder, nums };
});

const body = scans
  .map(({ folder, nums }) => `  scan("${folder}", [${nums.join(", ")}]),`)
  .join("\n");

writeFileSync(
  DATA,
  `// GENERATED by scripts/generate-brain-data.mjs - do not edit by hand.
// MRI brain scan sequences: one entry per folder in public/brain/.
// Playback fps per folder is configured in Hero.tsx.
export type BrainScan = {
  id: string;
  frames: string[];
};

const scan = (folder: string, nums: number[]): BrainScan => ({
  id: folder,
  frames: nums.map((n) => \`/brain/\${folder}/image_\${n}.png\`),
});

export const brainScans: BrainScan[] = [
${body}
];
`
);

for (const { folder, nums } of scans) {
  console.log(`${folder}: ${nums.length} frames`);
}
console.log("Wrote app/data/brains.ts and public/brain/");
